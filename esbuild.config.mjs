import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { mkdtemp, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

// Always allocate a fresh output directory; never overwrite a development installation.
const output = await mkdtemp(path.join(tmpdir(), "symlink-candidate-"));
const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(output, "main.js"),
	minify: prod,
});

for (const name of ["manifest.json", "styles.css"]) {
 await writeFile(path.join(output, name), await readFile(name));
}
console.log(`Candidate output: ${output}`);

if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
